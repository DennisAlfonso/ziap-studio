    [Fact]
    public async Task CatalogService_ResolvesSystemAndFileSourcesAndReportsMissingAssets()
    {
        using var workspace = new TestWorkspace();
        WriteActivePluginRegistry(workspace);
        workspace.WriteFile(
            "data/System.json",
            """
            {"sounds":[{"name":"ui/Cursor","volume":90,"pitch":100,"pan":0}]}
            """);
        workspace.WriteFile(
            "data/fusion/audio.json",
            """
            {
              "schemaVersion":1,
              "masterVolume":1,
              "categories":{"ui":{"volume":1}},
              "sounds":{
                "ui.navigate":{"category":"ui","source":{"kind":"systemSound","slot":"cursor"},"volume":45,"pitch":{"min":97,"max":103},"pan":0,"cooldown":25,"antiRepeat":false},
                "ui.open":{"category":"ui","source":{"kind":"files","files":["ui/Open","ui/Missing"]},"volume":50,"pitch":{"min":100,"max":100},"pan":0,"cooldown":0,"antiRepeat":true}
              }
            }
            """);
        workspace.WriteFile("audio/se/ui/Cursor.ogg");
        workspace.WriteFile("audio/se/ui/Open.ogg");
        var service = CreateCatalogService(new FileSystemService());
        var descriptor = CreateDescriptor();

        var document = await service.LoadAsync(
            CreateProject(workspace.RootPath),
            descriptor);

        Assert.True(document.PluginIsActive);
        Assert.Equal(2, document.EventCount);
        Assert.Equal(2, document.AssetCount);
        Assert.Contains(document.Assets, asset =>
            asset.EventId == "ui.navigate" && asset.SystemSlot == "cursor" && asset.Exists);
        Assert.Contains(document.Diagnostics, diagnostic =>
            diagnostic.Code == "sound.asset-missing" && diagnostic.EventId == "ui.open");
        Assert.False(document.IsValid);
    }

    [Fact]
    public void CatalogService_DiscoversRecursiveAudioFilesAndCollapsesFormatPairs()
    {
        using var workspace = new TestWorkspace();
        workspace.WriteFile("audio/se/Confirm.ogg");
        workspace.WriteFile("audio/se/Confirm.m4a");
        workspace.WriteFile("audio/se/ui/nested/Popup.wav");
        workspace.WriteFile("audio/se/ui/nested/Voice.mp3");
        workspace.WriteFile("audio/se/readme.txt");
        var service = CreateCatalogService(new FileSystemService());

        var files = service.DiscoverAudioFiles(CreateProject(workspace.RootPath));

        Assert.Equal(3, files.Count);
        var confirm = Assert.Single(files, option => option.CatalogPath == "Confirm");
        Assert.EndsWith("Confirm.ogg", confirm.ResolvedPath, StringComparison.OrdinalIgnoreCase);
        Assert.Equal(["OGG", "M4A"], confirm.Formats);
        Assert.Contains(files, option => option.CatalogPath == "ui/nested/Popup");
        Assert.Contains(files, option => option.CatalogPath == "ui/nested/Voice");
        Assert.DoesNotContain(files, option => option.CatalogPath.Contains("readme"));
    }

    [Fact]
    public async Task PlaybackResolver_AppliesVolumePitchAndPanContractToInMemoryCatalog()
    {
        using var workspace = new TestWorkspace();
        workspace.WriteFile("audio/se/ui/Upgrade.ogg");
        var service = CreateCatalogService(new FileSystemService());
        var resolver = new FusionAudioPlaybackResolver(
            service,
            new SequenceAudioRandomSource(),
            new ManualTimeProvider());
        var catalog = new FusionAudioCatalog
        {
            MasterVolume = 0.8,
            Categories = new Dictionary<string, FusionAudioCategory>
            {
                ["inspect"] = new() { Volume = 0.5 },
            },
        };
        var entry = new FusionAudioEntry
        {
            Category = "inspect",
            Source = new FusionAudioSource { Files = ["ui/Upgrade"] },
            Volume = 50,
            Pitch = new FusionAudioPitch { Min = 120, Max = 120 },
            Pan = 25,
        };

        var resolution = await resolver.ResolveAsync(
            CreateProject(workspace.RootPath),
            catalog,
            "inspect.upgrade",
            entry);

        var plan = Assert.IsType<FusionAudioPlaybackPlan>(resolution.Plan);
        Assert.Equal(FusionAudioPlaybackResolutionStatus.Ready, resolution.Status);
        Assert.Equal(0.20, plan.Volume, precision: 5);
        Assert.Equal(120, plan.Pitch);
        Assert.Equal(1.20, plan.PlaybackRate, precision: 5);
        Assert.Equal(0.25, plan.Pan, precision: 5);
        Assert.Equal("ui/Upgrade", plan.VariantId);
        Assert.EndsWith("audio/se/ui/Upgrade.ogg", plan.RelativePath);
    }

    [Fact]
    public async Task PlaybackResolver_RespectsCooldownAndAvoidsImmediateVariantRepeat()
    {
        using var workspace = new TestWorkspace();
        workspace.WriteFile("audio/se/A.ogg");
        workspace.WriteFile("audio/se/B.ogg");
        var clock = new ManualTimeProvider();
        var resolver = new FusionAudioPlaybackResolver(
            CreateCatalogService(new FileSystemService()),
            new SequenceAudioRandomSource(0, 0, 0),
            clock);
        var project = CreateProject(workspace.RootPath);
        var catalog = new FusionAudioCatalog();
        var entry = new FusionAudioEntry
        {
            Category = "inspect",
            Source = new FusionAudioSource { Files = ["A", "B"] },
            Pitch = new FusionAudioPitch { Min = 100, Max = 100 },
            AntiRepeat = true,
            Cooldown = 100,
        };

        var first = await resolver.ResolveAsync(project, catalog, "inspect.upgrade", entry);
        Assert.Equal("A", first.Plan!.VariantId);
        resolver.CommitPlayback(project, first.Plan);

        var suppressed = await resolver.ResolveAsync(project, catalog, "inspect.upgrade", entry);
        Assert.Equal(FusionAudioPlaybackResolutionStatus.Cooldown, suppressed.Status);
        Assert.Equal(100, suppressed.RemainingCooldownMs);

        clock.Advance(TimeSpan.FromMilliseconds(100));
        var second = await resolver.ResolveAsync(project, catalog, "inspect.upgrade", entry);
        Assert.Equal("B", second.Plan!.VariantId);
    }

