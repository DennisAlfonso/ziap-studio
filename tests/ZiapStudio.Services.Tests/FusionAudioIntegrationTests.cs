    [Fact]
    public async Task CatalogService_SavesValidCatalogAtomicallyAndProtectsExternalChanges()
    {
        using var workspace = new TestWorkspace();
        WriteActivePluginRegistry(workspace);
        workspace.WriteFile(
            "data/System.json",
            "{\"sounds\":[{\"name\":\"Cursor\",\"volume\":90,\"pitch\":100,\"pan\":0}]}");
        workspace.WriteFile("audio/se/Cursor.ogg");
        workspace.WriteFile(
            "data/fusion/audio.json",
            "{\"schemaVersion\":1,\"masterVolume\":1,\"categories\":{\"ui\":{\"volume\":1}},\"sounds\":{}}");
        var fileSystem = new FileSystemService();
        var service = CreateCatalogService(fileSystem);
        var project = CreateProject(workspace.RootPath);
        var loaded = await service.LoadAsync(project, CreateDescriptor());
        var catalog = loaded.Catalog with
        {
            Sounds = new Dictionary<string, FusionAudioEntry>
            {
                ["ui.navigate"] = new()
                {
                    Category = "ui",
                    Source = new FusionAudioSource
                    {
                        Kind = FusionAudioSourceKinds.SystemSound,
                        Slot = "cursor",
                    },
                    Volume = 45,
                    Pitch = new FusionAudioPitch { Min = 97, Max = 103 },
                    Cooldown = 25,
                },
            },
        };

        var snapshot = await service.SaveAsync(project, catalog, loaded.SourceSnapshot);

        Assert.NotEqual(loaded.SourceSnapshot!.ContentHash, snapshot.ContentHash);
        using var json = JsonDocument.Parse(await File.ReadAllBytesAsync(snapshot.SourcePath));
        Assert.True(json.RootElement.GetProperty("sounds").TryGetProperty("ui.navigate", out _));

        await File.AppendAllTextAsync(snapshot.SourcePath, " ");
        await Assert.ThrowsAsync<ExternalDocumentModificationException>(() =>
            service.SaveAsync(project, catalog with { MasterVolume = 0.9 }, snapshot));
    }

    [Fact]
    public async Task Preflight_MapsFusionAudioDiagnosticsToNavigableIssues()
    {
        using var workspace = new TestWorkspace();
        WriteActivePluginRegistry(workspace);
        workspace.WriteFile("data/System.json", "{\"sounds\":[]}");
        workspace.WriteFile(
            "data/fusion/audio.json",
            "{\"schemaVersion\":1,\"sounds\":{\"ui.confirm\":{\"source\":{\"kind\":\"files\",\"files\":[\"ui/Missing\"]},\"volume\":50,\"pitch\":{\"min\":100,\"max\":100},\"pan\":0,\"cooldown\":0}}}");
        var fileSystem = new FileSystemService();
        var registry = new RpgMakerPluginRegistryService(fileSystem);
        var catalog = new FusionAudioCatalogService(
            fileSystem,
            registry,
            new AtomicJsonFileWriter(fileSystem));
        var provider = new FusionAudioPreflightProvider(catalog, registry);

        var issues = await provider.ScanAsync(CreateProject(workspace.RootPath));

        var issue = Assert.Single(issues, issue => issue.RuleId == "fusion-audio.sound.asset-missing");
        Assert.Equal("FusionAudio", issue.Scope);
        Assert.Equal("ui.confirm", issue.RecordName);
        Assert.Equal("fusionaudio://catalog/event/ui.confirm", issue.NavigationTarget!.AbsoluteUri);
        Assert.Equal(PreflightSeverity.Error, issue.Severity);
    }

    private static FusionAudioCatalogService CreateCatalogService(FileSystemService fileSystem)
    {
        var registry = new RpgMakerPluginRegistryService(fileSystem);
        return new FusionAudioCatalogService(
            fileSystem,
            registry,
            new AtomicJsonFileWriter(fileSystem));
    }

    private static DocumentDescriptor CreateDescriptor() => new()
    {
        Id = new DocumentId("test:integration:fusion-audio"),
        DisplayName = "Fusion Audio",
        Kind = DocumentKind.ProjectIntegration,
        ResourceId = new Uri("fusionaudio://catalog/"),
    };

    private static void WriteActivePluginRegistry(TestWorkspace workspace) =>
        workspace.WriteFile(
            "js/plugins.js",
            "var $plugins = [{\"name\":\"zenkaiDevPlugins/ZDP_FusionAudio\",\"status\":true,\"parameters\":{}}];");

    private static ZiapProject CreateProject(string path) => new()
    {
        Id = "test",
        Name = "Test",
        ProjectType = KnownProjectTypes.RpgMakerMz,
        Path = path,
        IsZiapInitialized = true,
    };

    private sealed class SequenceAudioRandomSource(params double[] values)
        : IFusionAudioRandomSource
    {
        private readonly Queue<double> _values = new(values);

        public double NextDouble() => _values.Count > 0 ? _values.Dequeue() : 0;
    }

    private sealed class ManualTimeProvider : TimeProvider
    {
        private DateTimeOffset _utcNow = new(2026, 8, 19, 12, 0, 0, TimeSpan.Zero);

        public override DateTimeOffset GetUtcNow() => _utcNow;

        public void Advance(TimeSpan duration) => _utcNow += duration;
    }
